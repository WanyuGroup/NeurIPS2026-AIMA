def load_json(path: str) -> Dict[str, Any]:
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def save_json(data: Dict[str, Any], path: str):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)


def threaded_request(llms_instance, item, prompt_template, mode):
    try:
        if mode == "verify":
            prompt = prompt_template.format(question=item["question"], response=item["output"])
        else:
            prompt = prompt_template.format(content=item["output"])

        result = llms_instance.request(prompt)

        return {
            "id": item["id"],
            "result": result,
            "original_item": item,
        }
    except Exception as e:
        print(f"Error processing item {item.get('id', 'unknown')}: {e}")
        return None


def process_dataset_mode(dataset_name: str, items: List[Dict], mode: str, llm, num_threads: int) -> Dict[str, List[Dict]]:
    if not items:
        print(f"[{dataset_name}] No items for mode: {mode}")
        return {}

    print(f"[{dataset_name}] Processing {mode}: {len(items)} items...")

    if mode == "clarify":
        prompt_template = CLARIFY_PROMPTS.get(dataset_name, CLARIFY_PROMPTS["Art_and_Entertainment"])
    elif mode == "knowledge":
        prompt_template = KNOWLEDGE_PROMPTS.get(dataset_name, KNOWLEDGE_PROMPTS["Art_and_Entertainment"])
    elif mode == "verify":
        prompt_template = VERIFY_PROMPTS.get(dataset_name, VERIFY_PROMPTS["Art_and_Entertainment"])
    else:
        raise ValueError(f"Unknown mode: {mode}")

    results_map = {}
    with ThreadPoolExecutor(max_workers=num_threads) as executor:
        futures = [executor.submit(threaded_request, llm, item, prompt_template, mode) for item in items]

        for future in concurrent.futures.as_completed(futures):
            res = future.result()
            if res:
                results_map[res["id"]] = res

    processed_data = {}

    for item in items:
        item_id = item["id"]
        if item_id in results_map:
            llm_result = results_map[item_id]["result"]

            new_item = item.copy()

            if mode == "clarify":
                new_item["outline"] = llm_result
                new_item["question"] = new_item["question"] + "\nYou can refer to the following outlines: " + llm_result

            elif mode == "knowledge":
                new_item["knowledge"] = llm_result
                new_item["question"] = (
                    new_item["question"] + "\nYou can refer to the following general knowledge: " + llm_result
                )

            elif mode == "verify":
                new_item["verify"] = llm_result
                new_item["question"] = new_item["question"] + (
                    f"""You can refer to the revised version provided by the larger model below.
                    Process Description: {new_item["output"]}
                    Evaluation Results: {llm_result}
                    """
                )

            processed_data[item_id] = [new_item]

    return processed_data


def main():
    parser = argparse.ArgumentParser(description="Step 2: LLM Generation for Refined Questions")
    parser.add_argument(
        "--model_name",
        type=str,
        default="gpt-4o",
        help="Default cloud LLM for clarify / knowledge branches",
    )
    parser.add_argument(
        "--score_model_name",
        type=str,
        default="gpt-4o",
        help="Cloud LLM for verify (scoring / evaluation) branch",
    )
    parser.add_argument("--split", type=str, default="test", help="Dataset split (e.g., test, train)")
    parser.add_argument(
        "--stage",
        type=str,
        default="SFT_DPO",
        help="Must match Step 1 --stage for input filename alignment",
    )
    parser.add_argument(
        "--file_model_tag",
        type=str,
        default="Qwen2.5-7B-Instruct",
        help="Must match Step 1 --model_name for input/output filenames",
    )
    parser.add_argument("--input_dir", type=str, default="./data/")
    parser.add_argument(
        "--input_pattern",
        type=str,
        default="{file_model_tag}_{dataset}_{split}_{stage}_output.json",
    )
    parser.add_argument("--output_dir", type=str, default="./outputs/")
    parser.add_argument(
        "--output_pattern",
        type=str,
        default="{file_model_tag}_{dataset}_{split}_{stage}_step2_cloud.json",
    )
    parser.add_argument(
        "--datasets",
        nargs="+",
        default=["dataset_eval_A"],
        help="Must match Step 1 --dataset_names entries",
    )
    parser.add_argument("--num_threads", type=int, default=50)

    args = parser.parse_args()

    print("Arguments Configuration:")
    for k, v in vars(args).items():
        print(f"  {k}: {v}")
    print("=" * 40)

    llm_gen = LLMs(model=args.model_name, request_type="openai")
    llm_score = LLMs(model=args.score_model_name, request_type="openai")

    for dataset in args.datasets:
        input_filename = args.input_pattern.format(
            dataset=dataset,
            split=args.split,
            stage=args.stage,
            file_model_tag=args.file_model_tag,
        )
        input_path = os.path.join(args.input_dir, input_filename)

        if not os.path.exists(input_path):
            print(f"File not found: {input_path}, skipping...")
            continue

        print(f"\n====== Processing Dataset: {dataset} ======")
        raw_data = load_json(input_path)

        data_list = []
        if isinstance(raw_data, dict):
            for k, v in raw_data.items():
                if isinstance(v, list):
                    item = v[0]
                    item["id"] = k
                    data_list.append(item)
                else:
                    v["id"] = k
                    data_list.append(v)
        elif isinstance(raw_data, list):
            data_list = raw_data

        buckets = {"clarify": [], "knowledge": [], "verify": [], "origin": []}

        for item in data_list:
            aug_type = item.get("best_aug", "origin")
            if aug_type in buckets:
                buckets[aug_type].append(item)

        print(
            f"Distribution: Clarify={len(buckets['clarify'])}, "
            f"Knowledge={len(buckets['knowledge'])}, "
            f"Verify={len(buckets['verify'])}, "
            f"Origin={len(buckets['origin'])}"
        )

        combined_results = {}

        for item in buckets["origin"]:
            combined_results[item["id"]] = [item]

        for mode in ["clarify", "knowledge", "verify"]:
            active_llm = llm_score if mode == "verify" else llm_gen
            processed_subset = process_dataset_mode(dataset, buckets[mode], mode, active_llm, args.num_threads)
            if processed_subset:
                combined_results.update(processed_subset)

        output_filename = args.output_pattern.format(
            dataset=dataset,
            split=args.split,
            stage=args.stage,
            file_model_tag=args.file_model_tag,
        )
        output_path = os.path.join(args.output_dir, output_filename)

        save_json(combined_results, output_path)
        print(f"Saved ALL {len(combined_results)} items to {output_path}")


if __name__ == "__main__":
    main()
